public class Trace1 {
    public static void main(String[] args) {
        int a = 7;
        int b = 2;

        System.out.println(a / b);
        System.out.println(a / (double) b);
        System.out.println((double) (a / b));
        System.out.println(1 / 2 + 0.5);
        System.out.println(0.1 + 0.2);
    }
}